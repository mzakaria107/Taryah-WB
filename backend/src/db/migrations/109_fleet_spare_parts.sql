-- Spare parts catalog (قطع غيار) — optional multi-select tag when logging
-- a fleet expense or a completed maintenance service (fleet_expenses.part_ids /
-- fleet_maintenance_log.part_ids, both nullable int[]). Seeded from the fleet
-- coordinator's own parts list (سيارات مبردة/عادية — engine, clutch, differential,
-- driveshaft, brakes, suspension, steering, electrical, AC, tires/wheels, body,
-- general checks, then the refrigeration-unit section for reefer trucks), kept in
-- the SAME order as that source list — it's already grouped by mechanical system,
-- so preserving it (via sort_order) keeps related parts adjacent in the picker
-- instead of scrambling them alphabetically.
CREATE TABLE IF NOT EXISTS fleet_spare_parts (
  id          SERIAL PRIMARY KEY,
  name_ar     TEXT UNIQUE NOT NULL,
  is_active   BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order  INT NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

