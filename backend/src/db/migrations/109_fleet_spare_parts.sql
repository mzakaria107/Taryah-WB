-- Optional part tags on an expense/maintenance log row — nullable, no FK
-- constraint array-wide (Postgres can't FK into an array element list
-- directly); referential integrity here is enforced at the API layer
-- (fleet.js validates every id against fleet_spare_parts before saving),
-- same trust boundary as every other write in this file.
ALTER TABLE fleet_expenses        ADD COLUMN IF NOT EXISTS part_ids INTEGER[];
ALTER TABLE fleet_maintenance_log ADD COLUMN IF NOT EXISTS part_ids INTEGER[];
